"""Synthetic demo data: two runs of the same made-up weather and river station.

Nothing here comes from a real measurement. A fixed seed makes the files
identical on every machine, so the committed copies in ``examples/`` can be
checked against this generator.

``station_a`` plays the observations. ``station_b`` plays a model of the same
period: slightly biased, a little late and smoother, which gives the Compare tab
something to measure. Write the files with
``python -m eyeboard.services.demo examples``.
"""

import sys
from functools import lru_cache
from pathlib import Path

import numpy as np
import pandas as pd

from eyeboard.services.dataset import DataSource

DEMO_FILES = {
    "station_a": "demo_station_a.csv",
    "station_b": "demo_station_b.csv",
}
DEMO_LABELS = {
    "station_a": "Demo: station A (observations)",
    "station_b": "Demo: station B (model run)",
}
SEED = 20240301
START = "2024-03-01 00:00"
HOURS = 24 * 60  # two months, hourly


def _weather(rng: np.random.Generator) -> pd.DataFrame:
    """The 'true' signals, shared by both runs."""
    time = pd.date_range(START, periods=HOURS, freq="h")
    hours = np.arange(HOURS)
    day = 2 * np.pi * hours / 24
    season = 2 * np.pi * hours / (24 * 60)

    temperature = 8 + 5 * np.sin(season) + 4 * np.sin(day - 2.0)
    temperature += rng.normal(0, 0.6, HOURS)
    pressure = (
        1013 + 8 * np.sin(2 * np.pi * hours / (24 * 9)) + rng.normal(0, 0.8, HOURS)
    )

    # Rain comes as a few storms; the river answers with a delay and a long tail.
    rain = np.zeros(HOURS)
    for start in rng.choice(np.arange(24, HOURS - 48), size=9, replace=False):
        length = int(rng.integers(3, 14))
        rain[start : start + length] = rng.gamma(2.0, 1.4, length)
    kernel = np.exp(-np.arange(72) / 18.0)
    flow = 4.0 + 1.6 * np.convolve(rain, kernel)[:HOURS] + rng.normal(0, 0.15, HOURS)

    humidity = 70 - 1.8 * (temperature - 8) + 1.5 * rain + rng.normal(0, 2.0, HOURS)
    return pd.DataFrame(
        {
            "timestamp": time,
            "temperature_c": temperature,
            "humidity_pct": np.clip(humidity, 20, 100),
            "pressure_hpa": pressure,
            "rain_mm": rain,
            "flow_m3s": np.clip(flow, 0.5, None),
        }
    )


def _make(name: str) -> pd.DataFrame:
    rng = np.random.default_rng(SEED)
    table = _weather(rng)
    noise = np.random.default_rng(SEED + 1)

    if name == "station_b":
        # A model of the same period: 6 % too high, three hours late, no sensor noise.
        flow = table["flow_m3s"].rolling(5, center=True, min_periods=1).mean()
        table["flow_m3s"] = flow.shift(3, fill_value=flow.iloc[0]) * 1.06
        table["temperature_c"] = table["temperature_c"] + 0.8
        table = table.drop(columns=["humidity_pct"])
        table["status"] = "model"
    else:
        table["flow_m3s"] = table["flow_m3s"] + noise.normal(0, 0.1, HOURS)
        # A few lost readings, and a short maintenance window: things to find in Explore.
        holes = noise.choice(HOURS, size=40, replace=False)
        table.loc[holes, "humidity_pct"] = np.nan
        table["status"] = "ok"
        table.loc[500:520, "status"] = "maintenance"
        table.loc[500:520, "flow_m3s"] = np.nan
    table["site"] = "demo"
    table["timestamp"] = table["timestamp"].dt.strftime("%Y-%m-%d %H:%M")
    return table


@lru_cache(maxsize=len(DEMO_FILES))
def demo_csv(name: str) -> bytes:
    """The bytes of a demo file (comma-separated, dot decimals, UTF-8)."""
    table = _make(name)
    # An explicit line ending keeps the bytes equal on every operating system.
    return table.to_csv(index=False, float_format="%.3f", lineterminator="\n").encode(
        "utf-8"
    )


def demo_source(name: str) -> DataSource:
    """A data source for the app: the generated bytes, never written to disk."""
    return DataSource(
        key=f"demo:{name}:{SEED}",
        label=DEMO_FILES[name],
        kind="Demo",
        read_bytes=lambda: demo_csv(name),
    )


def write_examples(folder: str | Path) -> list[Path]:
    """Write the demo files into a folder and return their paths."""
    target = Path(folder)
    target.mkdir(parents=True, exist_ok=True)
    paths = []
    for name, filename in DEMO_FILES.items():
        path = target / filename
        path.write_bytes(demo_csv(name))
        paths.append(path)
    return paths


def main() -> None:
    """Write the demo files into the folder given as argument (default: examples)."""
    folder = sys.argv[1] if len(sys.argv) > 1 else "examples"
    for path in write_examples(folder):
        print(path)


if __name__ == "__main__":
    main()
